/*
# Create requests table for Rizwan Online Center

## Purpose
Stores customer service requests submitted from the request form on the
Rizwan Online Center site, and lets customers look up the status of their
request using a unique tracking ID.

This is a single-tenant, no-sign-in application: there is no login screen.
Anyone visiting the site can submit a request and look one up by tracking ID.
Accordingly, policies are scoped to `anon, authenticated` so the anon-key
frontend client can insert and select its own rows.

## New table: `requests`

- `id`            — uuid, primary key (generated automatically)
- `tracking_id`   — text, unique, NOT NULL. Human-readable tracking code in the
                    format `ROC` + 7 digits (e.g. `ROC1234567`). Generated by
                    the application at insert time and also enforced unique.
- `name`          — text, NOT NULL. Customer's full name.
- `phone`         — text, NOT NULL. 10-digit mobile number.
- `service`       — text, NOT NULL. The service title the customer needs help with.
- `message`       — text, nullable. Optional extra details the customer provided.
- `status`        — text, NOT NULL, default `'प्राप्त हुआ'`. Current status of the
                    request, shown on the tracking page. The app inserts with the
                    default; updates are intentionally not exposed to the public.
- `created_at`    — timestamptz, default `now()`. When the request was submitted.

## Security

- Row Level Security is ENABLED on `requests`.
- Grants:
  - `anon, authenticated` get SELECT, INSERT only. No UPDATE/DELETE from the
    public API — only a server-side (service role / admin) flow can change status
    or remove rows, which keeps request data tamper-proof from the browser.
- Policies (4, one per verb):
  - SELECT  — public read (anyone can look up a request by tracking ID).
  - INSERT  — public insert (anyone can submit a new request).
  - UPDATE  — denied from the public API (USING false). Status changes happen
              server-side only, where RLS is bypassed by the service role.
  - DELETE  — denied from the public API (USING false).

Because this is a no-auth, intentionally-public form + tracking lookup, the
SELECT and INSERT policies use `USING (true)` / `WITH CHECK (true)`. This is the
documented single-tenant pattern — it is correct here because every visitor is
meant to be able to submit and look up any request by tracking ID. The
UPDATE/DELETE policies explicitly deny access from the anon/authenticated roles
so a browser client cannot alter or remove submitted requests.

## Notes
1. No `user_id` column and no `auth.uid()` checks — this app has no sign-in.
2. `tracking_id` has a UNIQUE constraint so two requests can never share a code.
3. An index on `tracking_id` makes lookups fast even as the table grows.
*/

CREATE TABLE IF NOT EXISTS requests (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tracking_id text NOT NULL UNIQUE,
  name text NOT NULL,
  phone text NOT NULL,
  service text NOT NULL,
  message text,
  status text NOT NULL DEFAULT 'प्राप्त हुआ',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS requests_tracking_id_idx ON requests (tracking_id);

ALTER TABLE requests ENABLE ROW LEVEL SECURITY;

-- Public API can read (look up by tracking ID) and insert (submit a request).
-- No UPDATE / DELETE grant is given to anon/authenticated, so even though the
-- UPDATE/DELETE policies below exist, the roles lack the table privileges to
-- use them — defense in depth.
GRANT SELECT, INSERT ON requests TO anon, authenticated;

DROP POLICY IF EXISTS "public_select_requests" ON requests;
CREATE POLICY "public_select_requests"
ON requests FOR SELECT
TO anon, authenticated
USING (true);

DROP POLICY IF EXISTS "public_insert_requests" ON requests;
CREATE POLICY "public_insert_requests"
ON requests FOR INSERT
TO anon, authenticated
WITH CHECK (true);

-- Explicitly deny updates and deletes from the public API. Status changes are
-- performed server-side (service role bypasses RLS).
DROP POLICY IF EXISTS "deny_update_requests" ON requests;
CREATE POLICY "deny_update_requests"
ON requests FOR UPDATE
TO anon, authenticated
USING (false)
WITH CHECK (false);

DROP POLICY IF EXISTS "deny_delete_requests" ON requests;
CREATE POLICY "deny_delete_requests"
ON requests FOR DELETE
TO anon, authenticated
USING (false);
